"""Render constitution/repositories.md from constitution/repositories.json, and check the Stage 40 rule:
every active repository in the status matrix has an authoritative role and an integration boundary.

    python3 tools/build_constitution.py          # write the Markdown
    python3 tools/build_constitution.py --check  # exit 1 if out of date or a repository is missing
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "constitution" / "repositories.json"
OUT = ROOT / "constitution" / "repositories.md"
MATRIX = ROOT / "ecosystem" / "status-matrix.json"
REQUIRED = ("component", "kind", "owns", "never_owns", "interface", "integration_boundary", "blux", "visibility")
BLUX_VALUES = {"integrated", "standalone", "optional", "excluded"}


def render(doc: dict) -> str:
    lines = [
        "<!-- GENERATED by tools/build_constitution.py from constitution/repositories.json; edit the JSON. -->",
        "# Repository ownership map",
        "",
        f"As of {doc['as_of']}. Every active Outer-Void repository, its authority, what it never owns, its interface and its",
        "integration boundary. `blux` column: integrated (part of BLUX), standalone (works alone, BLUX can call it), optional",
        "(BLUX can add value, never required) or excluded (deliberately independent of BLUX).",
        "",
        "| Repository | Component | Kind | BLUX | Visibility |",
        "|---|---|---|---|---|",
    ]
    for r in doc["repositories"]:
        lines.append(f"| `{r['repo']}` | {r['component']} | {r['kind']} | {r['blux']} | {r['visibility']} |")
    for r in doc["repositories"]:
        lines += ["", f"## `{r['repo']}`: {r['component']}", "",
                  f"- **Owns:** {r['owns']}", f"- **Never owns:** {r['never_owns']}", f"- **Interface:** {r['interface']}",
                  f"- **Integration boundary:** {r['integration_boundary']}"]
        if r["depends_on"]:
            lines.append(f"- **Depends on:** {', '.join(f'`{d}`' for d in r['depends_on'])}")
    lines += ["", "## Not active", ""]
    lines += [f"- `{a['repo']}`: {a['note']}" for a in doc["archived"] + doc["excluded"]]
    return "\n".join(lines) + "\n"


def problems(doc: dict) -> list[str]:
    out = []
    mapped = {r["repo"] for r in doc["repositories"]}
    inactive = {a["repo"] for a in doc["archived"] + doc["excluded"]}
    for r in doc["repositories"]:
        out += [f"{r['repo']}: missing {k}" for k in REQUIRED if not str(r.get(k, "")).strip()]
        if r.get("blux") not in BLUX_VALUES:
            out.append(f"{r['repo']}: blux must be one of {sorted(BLUX_VALUES)}")
        out += [f"{r['repo']}: depends on unknown repository {d}" for d in r["depends_on"] if d not in mapped]
    matrix = json.loads(MATRIX.read_text())
    rows = matrix["components"] if isinstance(matrix, dict) else matrix
    active = {row["repo"].strip("`").split()[0] for row in rows if row.get("release_status") != "ARCHIVED"}
    out += [f"{repo}: in the status matrix but has no role or boundary in the ownership map" for repo in sorted(active - mapped - inactive)]
    out += [f"{repo}: in the ownership map but not in the status matrix" for repo in sorted(mapped - active)]
    return out


def main(argv: list[str]) -> int:
    doc = json.loads(SOURCE.read_text())
    errs = problems(doc)
    text = render(doc)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            errs.append("constitution/repositories.md is out of date: run python3 tools/build_constitution.py")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}")
    for e in errs:
        print(e, file=sys.stderr)
    if not errs:
        print("constitution OK")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
