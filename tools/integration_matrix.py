"""Render and check the cross-repository integration matrix (OV-61).

`ecosystem/integration-matrix.json` records, for one pin set, which boundary ran with which tests and what
happened: BLUX on (the integration tests with every BLUX_REQUIRE_* set) and BLUX off (each engine and `ax`
without the BLUX runtime). This tool renders `ecosystem/integration-matrix.md` and checks that:
- every result is one of PASS, FAIL, BLOCKED (with a decision or reason) and every PASS row has a test count;
- every pinned commit is a full SHA, and with --workspace, equals the pins in blux's integrations/targets.lock.json
  and the commits in ecosystem/compatibility.json (prefix match);
- the BLUX-off rows never list the BLUX runtime among the installed packages.

    python3 tools/integration_matrix.py                     # render
    python3 tools/integration_matrix.py --check [--workspace ~/ov]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "ecosystem" / "integration-matrix.json"
OUT = ROOT / "ecosystem" / "integration-matrix.md"
LOCK = ROOT / "ecosystem" / "compatibility.json"
RESULTS = {"PASS", "FAIL", "BLOCKED"}
SHA = re.compile(r"^[0-9a-f]{40}$")


def render(m: dict) -> str:
    lines = [
        "<!-- GENERATED by tools/integration_matrix.py from ecosystem/integration-matrix.json; do not edit. -->",
        "# Integration matrix",
        "",
        f"Pin set `{m['pin_set']}`, run {m['run_date']} ({m['stage']}). {m['summary']}",
        "",
        "## Pinned commits",
        "",
        "| Repository | Commit |",
        "|---|---|",
    ]
    lines += [f"| `{repo}` | `{sha[:12]}` |" for repo, sha in sorted(m["pins"].items())]
    lines += ["", "## BLUX on", "", "| Boundary | Tests | Count | Result | Note |", "|---|---|---|---|---|"]
    for r in m["blux_on"]:
        lines.append(f"| {r['boundary']} | {r['tests']} | {r.get('count', '-')} | {r['result']} | {r.get('note', '')} |")
    lines += ["", "## BLUX off", "", "| Component | How | Count | Result | Note |", "|---|---|---|---|---|"]
    for r in m["blux_off"]:
        lines.append(f"| {r['component']} | {r['how']} | {r.get('count', '-')} | {r['result']} | {r.get('note', '')} |")
    lines += ["", "## Method", ""] + [f"- {x}" for x in m["method"]]
    return "\n".join(lines) + "\n"


def problems(m: dict, workspace: Path | None) -> list[str]:
    out = []
    for repo, sha in m["pins"].items():
        if not SHA.match(sha):
            out.append(f"pin {repo}: not a full SHA")
    for section, key in (("blux_on", "boundary"), ("blux_off", "component")):
        for r in m[section]:
            if r["result"] not in RESULTS:
                out.append(f"{section} {r[key]}: unknown result {r['result']!r}")
            if r["result"] == "PASS" and not r.get("count"):
                out.append(f"{section} {r[key]}: PASS without a test count")
            if r["result"] == "BLOCKED" and not r.get("note"):
                out.append(f"{section} {r[key]}: BLOCKED needs a decision or reason")
    for r in m["blux_off"]:
        if any(p.lower().startswith("outervoid-blux") for p in r.get("packages", [])):
            out.append(f"blux_off {r['component']}: the BLUX runtime was installed")
    lock = json.loads(LOCK.read_text())["commits"]
    for repo, sha in m["pins"].items():
        if repo in lock and not sha.startswith(lock[repo]):
            out.append(f"pin {repo} {sha[:12]} differs from ecosystem/compatibility.json {lock[repo]}")
    if workspace is not None:
        targets = json.loads((workspace / "blux" / "integrations" / "targets.lock.json").read_text())["targets"]
        for t in targets:
            if m["pins"].get(t["name"]) != t["commit"]:
                out.append(f"pin {t['name']} differs from blux integrations/targets.lock.json {t['commit'][:12]}")
    return out


def main(argv: list[str]) -> int:
    m = json.loads(SRC.read_text())
    text = render(m)
    if "--check" in argv:
        ws = Path(argv[argv.index("--workspace") + 1]).expanduser() if "--workspace" in argv else None
        found = problems(m, ws)
        if OUT.read_text() != text if OUT.exists() else True:
            found.append("ecosystem/integration-matrix.md is out of date: run python3 tools/integration_matrix.py")
        for p in found:
            print(f"FAIL: {p}", file=sys.stderr)
        if not found:
            print("integration matrix OK")
        return 1 if found else 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
